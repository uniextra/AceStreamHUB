// GetText translates Spanish source text to lang, falling back to the input string.
func GetText(text, lang string) string {
	if lang == "" || lang == "es" {
		return text
	}
	if dict, ok := translations[lang]; ok {
		if v, exists := dict[text]; exists {
			return v
		}
	}
	return text
}
